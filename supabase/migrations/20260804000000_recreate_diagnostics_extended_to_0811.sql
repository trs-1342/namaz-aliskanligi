-- notification_location_diagnostics — YENİDEN OLUŞTURMA + pencere uzatma.
--
-- Neden gerekli: Orijinal tablo, yerleşik son-kullanma tarihi 2026-08-04 00:00 İstanbul
-- olan bir pg_cron job'ı (namaz-diagnostics-expiry) tarafından otomatik DROP edildi.
-- İstemci penceresi (LOCATION_DIAGNOSTICS_CUTOFF_ISO) 2026-08-11'e uzatıldığı için
-- sunucu tarafını da 2026-08-11'e taşıyoruz. Bu betik, minimize/harden sonrası SON
-- şema durumunu birebir yeniden kurar.
--
-- ÖNEMLİ: Kesim tarihi ÜÇ yerde geçer (CHECK, RLS policy, cron). Pencereyi tekrar
-- uzatırsan ÜÇÜNÜ DE ve istemcideki LOCATION_DIAGNOSTICS_CUTOFF_ISO'yu güncelle.
-- Bu sürümde kesim: 2026-08-11 00:00:00+03  (= 2026-08-10 21:00:00 UTC).

-- Güvenli yeniden kurulum için önce eski job/tablo/fonksiyonu temizle.
do $teardown$
declare
  existing_job_id bigint;
begin
  if exists (select 1 from pg_catalog.pg_extension where extname = 'pg_cron') then
    select jobid into existing_job_id from cron.job where jobname = 'namaz-diagnostics-expiry';
    if existing_job_id is not null then
      perform cron.unschedule(existing_job_id);
    end if;
  end if;
end
$teardown$;

drop table if exists public.notification_location_diagnostics;
drop function if exists public.enforce_notification_diagnostics_limits();

-- ------------------------------------------------------------------ tablo
create table public.notification_location_diagnostics (
  id bigint generated by default as identity primary key,
  installation_id uuid not null,
  tester_code text not null check (tester_code ~ '^[A-F0-9]{8}$'),
  device_name text,
  device_model text,
  operating_system text,
  operating_system_version text,
  app_version text,
  app_build_version text,
  notification_id text not null,
  notification_kind text not null check (notification_kind in ('prayer', 'early')),
  prayer_key text check (prayer_key in ('fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha')),
  notification_sent_at timestamptz not null,
  notification_scheduled_at timestamptz,
  captured_at timestamptz not null,
  capture_mode text not null check (capture_mode in ('foreground_received', 'android_alarm_cold_start')),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_m double precision check (accuracy_m is null or accuracy_m >= 0),
  altitude_m double precision,
  location_timestamp timestamptz not null,
  created_at timestamptz not null default now(),
  unique (installation_id, notification_id, notification_sent_at),
  constraint diagnostics_cutoff check (created_at < timestamptz '2026-08-11 00:00:00+03'),
  constraint diagnostics_device_name_size check (device_name is null or octet_length(device_name) <= 256),
  constraint diagnostics_device_model_size check (device_model is null or octet_length(device_model) <= 128),
  constraint diagnostics_operating_system_size check (operating_system is null or octet_length(operating_system) <= 64),
  constraint diagnostics_operating_system_version_size check (operating_system_version is null or octet_length(operating_system_version) <= 64),
  constraint diagnostics_app_version_size check (app_version is null or octet_length(app_version) <= 64),
  constraint diagnostics_app_build_version_size check (app_build_version is null or octet_length(app_build_version) <= 64),
  constraint diagnostics_notification_id_size check (octet_length(notification_id) <= 256)
);

comment on table public.notification_location_diagnostics is
  'Explicit-consent closed-test notification/location diagnostics; insert window ends 2026-08-10 23:59:59 Europe/Istanbul.';

-- ------------------------------------------------------------------ erişim (yalnız anon INSERT)
alter table public.notification_location_diagnostics enable row level security;

revoke all on table public.notification_location_diagnostics from public, anon, authenticated;
grant insert on table public.notification_location_diagnostics to anon;
grant usage on sequence public.notification_location_diagnostics_id_seq to anon;

create policy "temporary anonymous diagnostics insert"
on public.notification_location_diagnostics
for insert
to anon
with check (
  now() < timestamptz '2026-08-11 00:00:00+03'
  and created_at < timestamptz '2026-08-11 00:00:00+03'
);

-- ------------------------------------------------------------------ hız/kapasite sınırı
create or replace function public.enforce_notification_diagnostics_limits()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  perform pg_catalog.pg_advisory_xact_lock(1342, 20260803);

  if (select count(*) from public.notification_location_diagnostics) >= 2000 then
    raise exception 'diagnostics test capacity reached' using errcode = 'P0001';
  end if;

  if (
    select count(*)
      from public.notification_location_diagnostics
     where installation_id = new.installation_id
       and created_at >= pg_catalog.now() - interval '1 hour'
  ) >= 16 then
    raise exception 'diagnostics installation rate limit reached' using errcode = 'P0001';
  end if;

  return new;
end
$function$;

revoke all on function public.enforce_notification_diagnostics_limits() from public, anon, authenticated;

drop trigger if exists enforce_notification_diagnostics_limits
  on public.notification_location_diagnostics;
create trigger enforce_notification_diagnostics_limits
before insert on public.notification_location_diagnostics
for each row execute function public.enforce_notification_diagnostics_limits();

-- ------------------------------------------------------------------ otomatik son-kullanma (11 Ağustos)
-- İstersen bu bloğu silebilirsin; o zaman tablo elle silinene kadar kalır (ama insert'ler
-- yine de yukarıdaki CHECK/RLS ile 2026-08-11'de durur).
create extension if not exists pg_cron with schema pg_catalog;

do $schedule$
declare
  existing_job_id bigint;
begin
  select jobid into existing_job_id from cron.job where jobname = 'namaz-diagnostics-expiry';
  if existing_job_id is not null then
    perform cron.unschedule(existing_job_id);
  end if;
end
$schedule$;

-- 2026-08-10 21:05 UTC = 2026-08-11 00:05 İstanbul.
select cron.schedule(
  'namaz-diagnostics-expiry',
  '5 21 10 8 *',
  $job$
    do $expiry$
    begin
      if now() >= timestamptz '2026-08-11 00:00:00+03' then
        drop table if exists public.notification_location_diagnostics;
        drop function if exists public.enforce_notification_diagnostics_limits();
        perform cron.unschedule('namaz-diagnostics-expiry');
      end if;
    end
    $expiry$;
  $job$
);

