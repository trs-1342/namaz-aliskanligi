-- KURTARMA — tanılama tablosu düşürüldükten sonra testi yeniden açmak.
--
-- ── NE ZAMAN GEREKİR ────────────────────────────────────────────────────────
-- Günlük `namaz-diagnostics-expiry` job'ı, `public.diagnostics_cutoff()` geçince
-- `notification_location_diagnostics` tablosunu DÜŞÜRÜR. Bu doğru davranıştır
-- (verinin süresi dolar), ama şu tuzağı yaratır:
--
--   Kesim tarihini job çalıştıktan SONRA ileri alırsanız tablo geri gelmez.
--   Panelde `diagnostics_cutoff` uzatılmış görünür, cihazlar da pencereyi açık
--   sanar — ama her insert 404/PGRST205 alır. Üstelik bu, istemcide "gerçekten
--   kalıcı" sınıfıdır: üç doğrulanmış sinyalden sonra cihazlar KENDİNİ KAPATIR.
--
-- ── SIRA (ÖNEMLİ) ───────────────────────────────────────────────────────────
--   1) Önce `diagnostics_cutoff`'u ileri alın (yoksa yeni tablo aynı gece düşer):
--        update public.app_remote_config
--           set diagnostics_cutoff = timestamptz '2026-09-30 00:00:00+03'
--         where id = 1;
--   2) Bu betiği çalıştırın (tabloyu + kısıtları + RLS'i + trigger'ı kurar).
--   3) Kendini kapatmış cihazları geri getirin:
--        update public.app_remote_config
--           set kill_switch_reset_token = 'reset-' || now()::text
--         where id = 1;
--      (Cihazlar uygulama bir kez açıldığında dirilir; arka plan görevi kalıcı
--       kapanmada iptal olduğu için orada kendiliğinden dönemez.)
--
-- Betik idempotenttir: tablo zaten varsa hiçbir şey yapmaz, veri silmez.

do $recreate$
begin
  if to_regclass('public.notification_location_diagnostics') is not null then
    raise notice 'Tablo zaten var — hiçbir şey yapılmadı.';
    return;
  end if;

  create table public.notification_location_diagnostics (
    id bigint generated by default as identity primary key,
    installation_id uuid not null,
    tester_code text not null check (tester_code ~ '^[A-F0-9]{8}$'),
    device_name text,
    device_model text,
    operating_system text,
    operating_system_version text,
    app_version text,
    app_build_version text,
    notification_id text not null,
    notification_kind text not null check (notification_kind in ('prayer', 'early')),
    prayer_key text check (prayer_key in ('fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha')),
    notification_sent_at timestamptz not null,
    notification_scheduled_at timestamptz,
    captured_at timestamptz not null,
    capture_mode text not null check (capture_mode in ('foreground_received', 'android_alarm_cold_start')),
    -- Koordinatlar NULL olabilir: konum vermeyen testçiden de "hayatta" kaydı gelir.
    latitude double precision check (latitude between -90 and 90),
    longitude double precision check (longitude between -180 and 180),
    accuracy_m double precision check (accuracy_m is null or accuracy_m >= 0),
    altitude_m double precision,
    location_timestamp timestamptz,
    no_location_reason text,
    beacon_source text,
    created_at timestamptz not null default now(),
    unique (installation_id, notification_id, notification_sent_at),
    -- Kesim anı CHECK ile DEĞİL, RLS policy'siyle uygulanır (config'e bağlı olsun diye).
    constraint diagnostics_device_name_size check (device_name is null or octet_length(device_name) <= 256),
    constraint diagnostics_device_model_size check (device_model is null or octet_length(device_model) <= 128),
    constraint diagnostics_operating_system_size check (operating_system is null or octet_length(operating_system) <= 64),
    constraint diagnostics_operating_system_version_size check (operating_system_version is null or octet_length(operating_system_version) <= 64),
    constraint diagnostics_app_version_size check (app_version is null or octet_length(app_version) <= 64),
    constraint diagnostics_app_build_version_size check (app_build_version is null or octet_length(app_build_version) <= 64),
    constraint diagnostics_notification_id_size check (octet_length(notification_id) <= 256),
    constraint diagnostics_no_location_reason_valid check (
      no_location_reason is null
      or no_location_reason in (
        'permission_denied', 'services_disabled', 'position_unavailable',
        'background_no_fix', 'location_disabled_remotely'
      )
    ),
    constraint diagnostics_beacon_source_valid check (
      beacon_source is null
      or beacon_source in (
        'location_service', 'workmanager', 'foreground_timer', 'app_active',
        'net_reconnect', 'notification', 'gps_sync', 'manual', 'outbox_flush'
      )
    ),
    constraint diagnostics_location_or_reason check (
      (latitude is not null and longitude is not null) or no_location_reason is not null
    ),
    -- Tam olarak iki geçerli biçim: (koordinat + zaman damgası) ya da (neden).
    constraint diagnostics_location_timestamp_pairing check (
      (latitude is not null and longitude is not null
       and location_timestamp is not null and no_location_reason is null)
      or (latitude is null and longitude is null
          and location_timestamp is null and no_location_reason is not null)
    )
  );

  comment on table public.notification_location_diagnostics is
    'Explicit-consent closed-test notification/location diagnostics; window governed by app_remote_config.diagnostics_cutoff.';

  raise notice 'Tablo yeniden oluşturuldu.';
end
$recreate$;

-- ── PostGIS türev sütunları (20260804010000 ile aynı) ───────────────────────
-- PostGIS kurulu değilse bu blok sessizce atlanır; tablo yine çalışır.
do $generated$
begin
  if exists (select 1 from pg_catalog.pg_extension where extname = 'postgis')
     and not exists (
       select 1 from information_schema.columns
        where table_schema = 'public'
          and table_name = 'notification_location_diagnostics'
          and column_name = 'location'
     )
  then
    alter table public.notification_location_diagnostics
      add column location geography(Point, 4326)
        generated always as (
          case when latitude is not null and longitude is not null
               then st_setsrid(st_makepoint(longitude, latitude), 4326)::geography
          end
        ) stored,
      add column location_text text
        generated always as (
          case when latitude is not null and longitude is not null
               then latitude::text || ',' || longitude::text
          end
        ) stored,
      add column maps_url text
        generated always as (
          case when latitude is not null and longitude is not null
               then 'https://maps.google.com/?q=' || latitude::text || ',' || longitude::text
          end
        ) stored;
  end if;
end
$generated$;

-- ── Erişim: anon YALNIZ insert, pencere ve şalter config'ten ────────────────
alter table public.notification_location_diagnostics enable row level security;

revoke all on table public.notification_location_diagnostics from public, anon, authenticated;
grant insert on table public.notification_location_diagnostics to anon;
grant usage on sequence public.notification_location_diagnostics_id_seq to anon;

drop policy if exists "temporary anonymous diagnostics insert"
  on public.notification_location_diagnostics;
create policy "temporary anonymous diagnostics insert"
on public.notification_location_diagnostics
for insert
to anon
with check (
  public.diagnostics_enabled()
  and now() < public.diagnostics_cutoff()
  and created_at < public.diagnostics_cutoff()
);

-- ── Kapasite/hız trigger'ı (limitler config'ten) ────────────────────────────
drop trigger if exists enforce_notification_diagnostics_limits
  on public.notification_location_diagnostics;
create trigger enforce_notification_diagnostics_limits
before insert on public.notification_location_diagnostics
for each row execute function public.enforce_notification_diagnostics_limits();

notify pgrst, 'reload schema';

